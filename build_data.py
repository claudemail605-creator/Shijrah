#!/usr/bin/env python3
"""Regenerate js/data.js from the Excel database.

The website reads the .xlsx directly when served over http (e.g. VS Code
"Live Server"). data.js is the offline fallback used when index.html is opened
by double-clicking it (browsers block reading local files in that case).

Usage:  pip install openpyxl
        python tools/build_data.py
"""
import datetime as dt
import json
import pathlib

import openpyxl

root = pathlib.Path(__file__).resolve().parent.parent
xlsx = root / "data" / "Master_Family_Tree_Database.xlsx"
out = root / "js" / "data.js"

ws = openpyxl.load_workbook(xlsx, data_only=True)["Family_Data"]
rows = list(ws.iter_rows(values_only=True))
header = [str(h).strip() for h in rows[0]]


def clean(v):
    if v is None:
        return None
    if isinstance(v, (dt.datetime, dt.date)):
        return v.strftime("%d/%m/%Y")
    s = str(v).strip()
    return s or None


data = [
    {h: clean(v) for h, v in zip(header, r)}
    for r in rows[1:]
    if any(c is not None for c in r)
]
out.write_text(
    "// Auto-generated by tools/build_data.py - do not edit by hand.\n"
    "window.FAMILY_DATA = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n",
    encoding="utf-8",
)
print(f"Wrote {len(data)} people to {out}")
